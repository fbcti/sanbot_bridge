    /**
     * Class storing a three-byte RGB color.
     */
    public static class Color
    {
        /** Red value. */
        public final byte R;

        /** Green value. */
        public final byte G;

        /** Blue value. */
        public final byte B;

        /**
         * Constructs a new Color instance.
         *
         * The red, green, and blue integer values are converted to a bytes and copied to member
         * variables.
         *
         * @param   r           red value
         * @param   g           green value
         * @param   b           blue value
         */
        Color(int r, int g, int b)
        {
            R = (byte)(r & 0xFF);
            G = (byte)(g & 0xFF);
            B = (byte)(b & 0xFF);
        }
    }
