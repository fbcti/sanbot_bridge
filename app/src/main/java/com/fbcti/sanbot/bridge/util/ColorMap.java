/**
 * Provides palettes for depth image encoding.
 *
 * The following palettes are implemented:
 * - rainbow: violet - blue - green - yellow - orange - red,
 * - turbo: dark blue - cyan - green - yellow - orange - red/dark red,
 * - viridis: dark blue/purple - teal -  green - yellow,
 * - inferno: black/dark purple -  red -  orange - yellow,
 * - default: black - dark yellow - light yellow
 *
 * @version     1.0.001
 * @date        21 Aug 2026
 * @author      Ferry Blaazer
 * @copyright   2026 FBCTI
 */
