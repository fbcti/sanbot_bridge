    /**
     * Returns the palette created from an array of colors.
     *
     * The array of colors should contain exactly 256 entries, each entry itself an array specifying
     * the red, green and blue values.
     *
     * @param   colors          byte array specifying colors
     *
     * @return  palette as array of Color instances
     */
    @NonNull
    private Color[] toPalette(int[][] colors)
    {
        Color[] c = new Color[256];
        for (int i=0; i<256; i++) c[i] = new Color(colors[i][0], colors[i][1], colors[i][2]);
        return c;
    }

