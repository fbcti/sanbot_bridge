    /** Rainbow palette id. */
    public static final int PALETTE_RAINBOW = 1;

    /** Turbo palette id. */
    public static final int PALETTE_TURBO = 2;

    /** Viridis palette id. */
    public static final int PALETTE_VIRIDIS = 3;

    /** Inferno palette id. */
    public static final int PALETTE_INFERNO = 4;

    /** Temperature palette id. */
    public static final int PALETTE_TEMPERATURE = 5;

    /***********************************************************************************************
     * PUBLIC METHODS
     **********************************************************************************************/
    @NonNull
    /**
     * Returns the color palette id matching the specified palette name.
     *
     * @param   paletteName     color palette name
     *
     * @return  palette id as integer, or 0 if palette with specified name does not exist
     */
    public static int getPaletteId(@NonNull String paletteName)
    {
        switch (paletteName)
        {
            case "rainbow":
                return PALETTE_RAINBOW;
            case "turbo":
                return PALETTE_TURBO;
            case "viridis":
                return PALETTE_VIRIDIS;
            case "inferno":
                return PALETTE_INFERNO;
            case "temp":
                return PALETTE_TEMPERATURE;
            default:
                return 0;
        }
    }

    /**
     * Returns the color palette with the specified id.
     *
     * If the palette with the specified id does not exist the default palette is returned.
     *
     * @param   paletteId     name of palette to return
     *
     * @return  array of Color instances
     */
    public static Color[] getPalette(int paletteId)
    {
        switch (paletteId)
        {
            case PALETTE_RAINBOW:
                return new ColorMap().getRainbowPalette();
            case PALETTE_TURBO:
                return new ColorMap().getTurboPalette();
            case PALETTE_VIRIDIS:
                return new ColorMap().getViridisPalette();
            case PALETTE_INFERNO:
                return new ColorMap().getInfernoPalette();
            case PALETTE_TEMPERATURE:
                return new ColorMap().getTemperaturePalette();
            default:
                return new ColorMap().getDefaultPalette();
        }
    }

    /***********************************************************************************************
     * PRIVATE METHODS
     **********************************************************************************************/

    /**
     * Returns the default palette.
     *
     * @return  defaut palette as array of Color instances
     */
    @NonNull
    private Color[] getDefaultPalette()
    {
        Color[] colors = new Color[256];
        for (int i=0; i<256; i++) colors[i] = new Color(i, (i*235 + 127)/255, (i*31 + 127)/255);
        return colors;
    }

    @NonNull
    /**
     * Returns the rainbow palette.
     *
     * @return  defaut palette as array of Color instances
     */
    private Color[] getRainbowPalette()
    {
        Color[] colors = new Color[256];
        for (int i=0; i<256; i++)
        {
            if (i <= 29)
            {
                colors[i] = new Color((int)Math.round(129.36 - i*4.36), 0, 255);
            }
            else if (i <= 86)
            {
                colors[i] = new Color(0, (int)Math.round(-133.54 + i*4.52), 255);
            }
            else if (i <= 141)
            {
                colors[i] = new Color(0, 255, (int)Math.round(665.83 - i*4.72));
            }
            else if (i <= 199)
            {
                colors[i] = new Color((int)Math.round(-635.26 + i*4.47), 255, 0);
            }
            else
            {
                colors[i] = new Color(255, (int)Math.round(1166.81 - i*4.57), 0);
            }
        }
        return colors;
    }

